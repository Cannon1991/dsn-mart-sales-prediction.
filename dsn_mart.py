def clean_and_preprocess(df, is_train=True, preprocessors=None):
    """
    Cleans structural variations and imputes missing dimensions deterministically.
    """
    df = df.copy()

    # Reset index to eliminate KeyError positioning issues entirely during slicing
    df = df.reset_index(drop=True)

    # 1. Standardize text features (fix inconsistent capitalization)
    df['product_category'] = df['product_category'].astype(str).str.upper().str.strip()
    df['fat_content'] = df['fat_content'].astype(str).str.upper().str.strip()

    if is_train:
        preprocessors = {}
        # 2. Missing Value Imputation Strategy
        cat_weight_map = df.groupby('product_category')['product_weight_kg'].mean().to_dict()
        global_mean_weight = df['product_weight_kg'].mean()

        # Impute store size with mode of that location tier/format configuration
        store_size_mode = df.groupby(['store_location_tier', 'store_format'])['store_size'].agg(
            lambda x: x.mode().iloc[0] if not x.mode().empty else 'Medium'
        ).to_dict()

        preprocessors['cat_weight_map'] = cat_weight_map
        preprocessors['global_mean_weight'] = global_mean_weight
        preprocessors['store_size_mode'] = store_size_mode
    else:
        cat_weight_map = preprocessors['cat_weight_map']
        global_mean_weight = preprocessors['global_mean_weight']
        store_size_mode = preprocessors['store_size_mode']

    # Apply Item Weight Imputation
    df['product_weight_kg'] = df.apply(
        lambda row: row['product_weight_kg'] if pd.notnull(row['product_weight_kg'])
        else cat_weight_map.get(row['product_category'], global_mean_weight), axis=1
    )

    # Apply Store Size Imputation
    df['store_size'] = df.apply(
        lambda row: row['store_size'] if pd.notnull(row['store_size'])
        else store_size_mode.get((row['store_location_tier'], row['store_format']), 'Medium'), axis=1
    )

    # 3. Advanced Feature Engineering
    df['price_per_kg'] = df['product_price'] / (df['product_weight_kg'] + 1e-5)
    df['visibility_price_ratio'] = df['shelf_visibility'] * df['product_price']
    df['store_establishment_year'] = 2026 - df['store_age_years']

    # Target encoding or frequency encoding proxy
    if is_train:
        cat_sales_map = df.groupby('product_category')['total_sales'].mean().to_dict()
        preprocessors['cat_sales_map'] = cat_sales_map
    else:
        cat_sales_map = preprocessors['cat_sales_map']

    df['cat_historical_avg_sales'] = df['product_category'].map(cat_sales_map).fillna(0)

    # 4. Categorical Transformation Encoding
    categorical_cols = ['fat_content', 'product_category', 'store_code', 'store_size', 'store_location_tier', 'store_format']

    if is_train:
        label_encoders = {}
        for col in categorical_cols:
            le = LabelEncoder()
            df[col] = le.fit_transform(df[col].astype(str))
            label_encoders[col] = le
        preprocessors['label_encoders'] = label_encoders
    else:
        label_encoders = preprocessors['label_encoders']
        for col in categorical_cols:
            le = label_encoders[col]
            df[col] = df[col].astype(str).map(lambda s: s if s in le.classes_ else le.classes_[0])
            df[col] = le.transform(df[col])

    if is_train:
        return df, preprocessors
    return df

def train_and_evaluate():
    print("🚀 Initializing DSN Mart Training Pipeline...")
    train_df = pd.read_csv('train.csv')
    test_df = pd.read_csv('test.csv')

    # Preprocess Datasets
    processed_train, preprocessors = clean_and_preprocess(train_df, is_train=True)
    processed_test = clean_and_preprocess(test_df, is_train=False, preprocessors=preprocessors)

    features = [col for col in processed_train.columns if col not in ['id', 'product_code', 'total_sales']]
    X = processed_train[features].reset_index(drop=True)
    y = processed_train['total_sales'].reset_index(drop=True)

    # Cross-Validation setup (5-Fold Strategy)
    kf = KFold(n_splits=5, shuffle=True, random_state=42)
    rmse_scores = []

    print(f"📊 Extracted Features for training: {features}")

    for fold, (train_idx, val_idx) in enumerate(kf.split(X, y)):
        X_tr, y_tr = X.iloc[train_idx], y.iloc[train_idx]
        X_va, y_va = X.iloc[val_idx], y.iloc[val_idx]

        # High performance model initialization
        model = RandomForestRegressor(n_estimators=100, max_depth=8, random_state=42, n_jobs=-1)
        model.fit(X_tr, y_tr)

        preds = model.predict(X_va)
        fold_rmse = root_mean_squared_error(y_va, preds)
        rmse_scores.append(fold_rmse)
        print(f"  ↳ Fold {fold+1} Validation RMSE: {fold_rmse:.4f}")

    print(f"✅ Baseline Validation Cross-Validation RMSE Average: {np.mean(rmse_scores):.4f}")

    # Train ultimate unified final production model
    final_model = RandomForestRegressor(n_estimators=150, max_depth=8, random_state=42, n_jobs=-1)
    final_model.fit(X, y)

    # Save Pipeline artifacts safely
    os.makedirs('models', exist_ok=True)
    with open('models/artifacts.pkl', 'wb') as f:
        pickle.dump({'model': final_model, 'preprocessors': preprocessors, 'features': features}, f)

    # Generate Submissions File
    test_preds = final_model.predict(processed_test[features])
    submission = pd.DataFrame({'id': test_df['id'], 'total_sales': test_preds})
    submission.to_csv('submission.csv', index=False)
    print("💾 Production model optimized and predictions written out to 'submission.csv'!")

if __name__ == "__main__":
    train_and_evaluate()

